#!/usr/bin/env python3
"""Build and solve the order-10 band LP on the rebuilt 8-root envelope.

This is the certificate the repository set out to produce, on rows that are
actually valid.  Primal, over the 12,172 order-10 states:

    maximise  eta
    q >= 0,  sum q = 1,  LO <= <d_edge, q> <= HI,  <m, q> >= 0   (fixed Gram row)
    u_tau <= <h_{tau,c}, q>       for every rule c in the pool of root type tau
    eta   <= -2/25 + sum_tau u_tau

For a genuine triangle-free graphon W with state vector q(W) the point
`(q(W), u_tau = min over the pool, eta = sum u - 2/25)` is feasible, and
`d_mono(W) <= U8(W) <= sum_tau min_pool <= eta`, so a dual objective `delta`
proves `d_mono(W) <= 2/25 + delta` on the closed band.  `delta <= 0` is the
conjecture there.

Rows come from `rebuild_u8.py` (validated at the balanced C5 blow-up to machine
epsilon).  Summing over all isomorphisms root -> type is organised by orbits:
for each root type the ordered profile pairs are partitioned into Aut-orbits,
`N[o, s]` counts the raw incidences of orbit `o` in state `s`, and a rule `c`
contributes `f_c(o)` = fraction of pairs in `o` that `c` colours alike, so

    <h_{tau,c}, q>  =  (1/90) sum_o f_c(o) <N[o,:], q>.

Rules are generated by cutting planes: at each LP optimum `q*` the best rule
per root is a weighted MaxCut over the profile closure; a rule whose value
undercuts `u_tau*` becomes a new row.  The pool is seeded with the constant
rule (valid, weak) and with the MaxCut rules at a few genuine graphons.
"""

